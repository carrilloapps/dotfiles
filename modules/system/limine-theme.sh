#!/usr/bin/env bash
# RedRog look for the Limine boot menu: absolute black background, text in
# the theme colors only, accent-red title; and a short menu (1 s, any key
# stops it to pick another entry), so booting is not held up. Installed by modules/system (with the palette
# filled in) as /usr/local/lib/redrog/limine-theme.sh and run again by the
# pacman hook zz-redrog-limine.hook after kernel, Limine or theme updates.
#
# Limine uses the LAST value of each option, so the RedRog block goes right
# before the first boot entry and other appearance options (such as the theme
# CachyOS ships) are commented out with "#redrog-off#". The boot entries are
# counted before and after; if they changed, the backup is restored.
# Usage: limine-theme.sh [BACKUP_DIR]
set -euo pipefail
LC=/boot/limine.conf
[ -f "$LC" ] || exit 0
BK="${1:-/var/backups/redrog/limine-$(date +%Y%m%d-%H%M%S)}"
mkdir -p "$BK"
cp "$LC" "$BK/limine.conf"
BEFORE=$(grep -c '^/' "$LC" || true)

BLOCK=$(mktemp)
trap 'rm -f "$BLOCK"' EXIT
# Absolute black background. Limine draws some text in palette colour 0
# ("black") and other parts in colours 2-5, so every slot is a readable theme
# colour: 0 and 6 the dim gray, 1/4 the accent red, 2/5 the lighter red, 3
# and 7 the text white. Branding and help colours are RRGGBB values (Limine
# 10+; a palette index such as "1" reads as 000001, black on black, and only
# the boot entries were left on screen).
cat > "$BLOCK" <<BLK
# >>> REDROG (generated by RedRog: modules/system)
timeout: 1
backdrop: 000000
term_background: 000000
term_background_bright: 000000
term_foreground: @FG@
term_foreground_bright: ffffff
term_palette: @FG_DIM@;@ACCENT@;@ACCENT_ALT@;@FG@;@ACCENT@;@ACCENT_ALT@;@FG_DIM@;@FG@
term_palette_bright: @FG_DIM@;@ACCENT_ALT@;@ACCENT_ALT@;ffffff;@ACCENT_ALT@;@ACCENT_ALT@;@FG_DIM@;ffffff
term_margin: 96
interface_branding: @BRANDING@
interface_branding_colour: @ACCENT@
interface_help_colour: @FG_DIM@
interface_help_colour_bright: @FG@
# <<< REDROG
BLK

python3 -I - "$LC" "$BLOCK" <<'PY'
import re, sys
conf, block = sys.argv[1:]
text = open(conf, encoding="utf-8").read()
text = re.sub(r"(?ms)^# >>> (REDROG|ROG-MODERNO|NEONGRID).*?^# <<< \1[^\n]*\n?", "", text)
lines = text.split("\n")
first = next((i for i, l in enumerate(lines) if l.startswith("/")), len(lines))
look = re.compile(r"^(timeout|wallpaper|wallpaper_style|backdrop|term_[a-z_]+|interface_(branding|branding_colou?r|help_colou?r|help_colou?r_bright|help_hidden)):")
for i in range(first):
    if look.match(lines[i]):
        lines[i] = "#redrog-off# " + lines[i]
lines[first:first] = open(block, encoding="utf-8").read().rstrip("\n").split("\n") + [""]
open(conf, "w", encoding="utf-8").write("\n".join(lines))
PY

AFTER=$(grep -c '^/' "$LC" || true)
if [ "$BEFORE" != "$AFTER" ]; then
  cat "$BK/limine.conf" > "$LC"
  echo "RedRog: Limine boot entries changed ($BEFORE -> $AFTER), backup restored" >&2
  exit 1
fi

# A "Windows Boot Manager" entry left from an earlier Windows install is
# removed while no EFI partition holds Windows' boot manager (it booted
# nothing). If Windows comes back, limine-entry-tool detects it again.
win=0
while read -r dev type; do
  [ "$type" = c12a7328-f81f-11d2-ba4b-00a0c93ec93b ] || continue
  mnt=$(findmnt -n -o TARGET "/dev/$dev" | head -1)
  if [ -n "$mnt" ]; then
    [ -e "$mnt/EFI/Microsoft/Boot/bootmgfw.efi" ] && win=1
  else
    tmp=$(mktemp -d)
    if mount -o ro "/dev/$dev" "$tmp" 2>/dev/null; then
      [ -e "$tmp/EFI/Microsoft/Boot/bootmgfw.efi" ] && win=1
      umount "$tmp"
    fi
    rmdir "$tmp"
  fi
done < <(lsblk -rno NAME,PARTTYPE)
if [ "$win" = 0 ] && grep -q '^ *//Windows Boot Manager' "$LC"; then
  python3 -I - "$LC" <<'PY'
import re, sys
p = sys.argv[1]
text = open(p, encoding="utf-8").read()
# the entry: its title line and the indented option lines under it
text = re.sub(r"(?m)^[ \t]*//Windows Boot Manager\n(?:[ \t]+[a-z_]+:.*\n)*", "", text)
open(p, "w", encoding="utf-8").write(text)
PY
  echo "RedRog: removed the Windows Boot Manager entry (no Windows on this machine)"
fi
# With config verification the checksum must be re-enrolled after any edit
if command -v limine-enroll-config >/dev/null; then
  limine-enroll-config >/dev/null
fi
