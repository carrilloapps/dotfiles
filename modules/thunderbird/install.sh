#!/usr/bin/env bash
# Thunderbird like macOS Mail, in RedRog colors: three columns (folders, the
# message list as cards, the message), macOS traffic lights instead of the
# GTK window buttons, rounded selections and the RedRog palette on the panes
# (userChrome.css). Applied to the default profile while Thunderbird is closed.
# describe: Thunderbird like macOS Mail | Thunderbird como Mail de macOS

TB=""
for d in "$CONFIG_HOME/thunderbird" "$REAL_HOME/.thunderbird"; do
  [ -f "$d/profiles.ini" ] && { TB="$d"; break; }
done
[ -n "$TB" ] || { info "$(L "Thunderbird has no profile yet: skipped" "Thunderbird no tiene perfil todavía: se omite")"; return 0; }
PROFILE=$(awk -F= '/^\[Install/{f=1} f&&/^Default=/{print $2; exit}' "$TB/profiles.ini")
P="$TB/$PROFILE"
[ -d "$P" ] || { warn "$(L "Thunderbird profile not found:" "no encuentro el perfil de Thunderbird") $PROFILE"; return 0; }
if pgrep -x thunderbird >/dev/null; then
  warn "$(L "close Thunderbird and run: ./install.sh --only thunderbird" "cierra Thunderbird y ejecuta: ./install.sh --only thunderbird")"
  return 0
fi
if [ "$DRY_RUN" = 1 ]; then info "[dry-run] user.js, chrome/userChrome.css → $P"; return 0; fi
mkdir -p "$P/chrome"
for f in user.js chrome/userChrome.css; do
  if [ -f "$P/$f" ] && ! grep -q 'RedRog' "$P/$f"; then cp "$P/$f" "$P/$f.before-redrog"; fi
done

cat > "$P/user.js" <<EOF
// Generated by RedRog (modules/thunderbird) — overwritten on reinstall
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
// the system theme: light or dark as the system, which follows the RedRog switch
user_pref("extensions.activeThemeID", "default-theme@mozilla.org");
// three columns like Mail: folders | message list | message
user_pref("mail.pane_config.dynamic", 2);
// the message list as cards, like Mail
user_pref("mail.threadpane.listview", 0);
user_pref("mail.uidensity", 1);
EOF

cat > "$P/chrome/userChrome.css" <<EOF
/* Generated by RedRog (modules/thunderbird) */
:root {
  --rr-bg: #$BG; --rr-surface: #$SURFACE; --rr-hi: #$SURFACE_HI;
  --rr-sel: #$SELECTION; --rr-fg: #$FG; --rr-dim: #$FG_DIM; --rr-accent: #$ACCENT;
  --layout-background-0: var(--rr-bg) !important;
  --layout-background-1: var(--rr-bg) !important;
  --layout-background-2: var(--rr-surface) !important;
  --layout-color-1: var(--rr-fg) !important;
  --layout-color-2: var(--rr-dim) !important;
  --layout-border-0: var(--rr-hi) !important;
  --layout-border-1: var(--rr-hi) !important;
  --toolbar-bgcolor: var(--rr-bg) !important;
  --toolbar-color: var(--rr-fg) !important;
  --tabs-toolbar-background-color: var(--rr-bg) !important;
  --tab-selected-bgcolor: var(--rr-surface) !important;
  --spaces-bg-color: var(--rr-bg) !important;
  --foldertree-background: #161616 !important;
  --sidebar-background-color: #161616 !important;
  --treeitem-background-selected: var(--rr-sel) !important;
  --treeitem-background-active: var(--rr-hi) !important;
  --listbox-selected-bg: var(--rr-hi) !important;
  --selected-item-color: var(--rr-hi) !important;
  --selected-item-text-color: var(--rr-fg) !important;
  --focus-outline-color: var(--rr-accent) !important;
}

/* macOS traffic lights: the KWin titlebar drawings (made by modules/gtk) */
.titlebar-buttonbox { gap: 6px !important; padding-inline: 12px 8px !important; align-items: center !important; }
.titlebar-button {
  appearance: none !important; -moz-default-appearance: none !important;
  width: 14px !important; height: 14px !important; min-width: 14px !important; min-height: 14px !important;
  padding: 0 !important; margin: 0 !important; border: none !important; box-shadow: none !important;
  background: transparent center / 14px 14px no-repeat !important;
}
.titlebar-button > .toolbarbutton-icon { display: none !important; }
.titlebar-close { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/close-active.svg") !important; }
.titlebar-min { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/minimize-active.svg") !important; }
.titlebar-max, .titlebar-restore { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/maximize-active.svg") !important; }
.titlebar-buttonbox:hover .titlebar-close { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/close-hover.svg") !important; }
.titlebar-buttonbox:hover .titlebar-min { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/minimize-hover.svg") !important; }
.titlebar-buttonbox:hover .titlebar-max, .titlebar-buttonbox:hover .titlebar-restore { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/maximize-hover.svg") !important; }
.titlebar-close:active { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/close-pressed.svg") !important; }
.titlebar-min:active { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/minimize-pressed.svg") !important; }
.titlebar-max:active, .titlebar-restore:active { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/maximize-pressed.svg") !important; }
:root:-moz-window-inactive .titlebar-buttonbox:not(:hover) .titlebar-button { background-image: url("file://$CONFIG_HOME/gtk-4.0/redrog-lights/close-inactive.svg") !important; }

/* Folder sidebar a shade darker than the list, like Mail's sidebar */
#folderPane, #folderTree, #spacesToolbar { background-color: #161616 !important; }
#threadPane, #threadTree, #messagePane, #messageBrowser, #unifiedToolbar, #tabs-toolbar,
#navigation-toolbox { background-color: var(--rr-bg) !important; color: var(--rr-fg) !important; }

/* Rounded, inset selections in the sidebar and the list */
#folderTree li > .container { border-radius: 6px !important; margin-inline: 6px !important; }
#threadTree tr.card-layout td, #threadTree tr[is="thread-card"] { border-radius: 10px !important; }
#threadTree tr.selected, #folderTree li.selected > .container { background-color: var(--rr-sel) !important; }
#threadTree tr.selected:focus-within, #folderTree:focus-within li.selected > .container { background-color: var(--rr-hi) !important; }

/* Unread dot and focus in the accent color */
.unread-icon, #threadTree tr.unread .subject-line { color: var(--rr-accent) !important; }

/* Tabs: soft, rounded, no accent line */
.tab-background { border-radius: 8px !important; border: none !important; }
.tab-background[selected] { background: var(--rr-surface) !important; outline: 1px solid var(--rr-hi) !important; }
.tab-line { display: none !important; }

/* No light GTK borders: flat buttons and fields, like Mail's toolbar */
:root {
  --button-border-color: transparent !important;
  --button-background-color: transparent !important;
  --button-hover-background-color: var(--rr-hi) !important;
  --button-active-background-color: var(--rr-sel) !important;
  --toolbarbutton-hover-background: var(--rr-hi) !important;
  --toolbarbutton-active-background: var(--rr-sel) !important;
  --toolbarbutton-border-radius: 6px !important;
  --toolbar-field-border-color: transparent !important;
  --toolbar-field-background-color: var(--rr-surface) !important;
  --splitter-color: var(--rr-hi) !important;
  --sidebar-border-color: var(--rr-hi) !important;
  --in-content-box-border-color: var(--rr-hi) !important;
}
button, toolbarbutton, .button, menulist, .toolbarbutton-1 {
  appearance: none !important;
  border-color: transparent !important;
  box-shadow: none !important;
}
button:not(:disabled):hover, toolbarbutton:not([disabled]):hover, menulist:hover {
  background-color: var(--rr-hi) !important;
}
/* "New message": the only filled button, in the accent color */
#folderPaneWriteButton { background-color: var(--rr-accent) !important; color: #fff !important; border-radius: 8px !important; }
#folderPaneWriteButton:hover { filter: brightness(1.08); }
/* Search field and other inputs: soft pill, no frame */
#unifiedToolbar search-bar, global-search-bar, input, html|input, search-textbox {
  border-color: transparent !important; box-shadow: none !important;
}
#unifiedToolbarContent .search-bar, global-search-bar {
  --search-bar-background: var(--rr-surface) !important; --search-bar-border-color: transparent !important;
  border-radius: 8px !important;
}
/* Pane splitters and the Today pane: thin, dark hairlines */
splitter, hr, .splitter, #today-splitter, #folderPaneSplitter, #messagePaneSplitter {
  border-color: var(--rr-hi) !important; background-color: var(--rr-hi) !important;
  min-width: 1px !important; min-height: 1px !important;
}
#today-pane-panel, #agenda, #agenda-container, .agenda-container { background-color: #161616 !important; border: none !important; }
#mini-day-box, #agenda-toolbar, .today-pane-header { background-color: #161616 !important; border: none !important; }
#messageHeader, .message-header-container, #header-view-toolbox { border-color: transparent !important; background-color: var(--rr-bg) !important; }
EOF
# light or dark as the system (the RedRog light/dark switch sets it)
read -r l_bg l_surface l_hi l_sel l_fg l_dim l_accent < <(REDROG_VARIANT=light HOME="$REAL_HOME" bash -c \
  'source "$REDROG_ROOT/lib/palette.sh"; echo "$BG $SURFACE $SURFACE_HI $SELECTION $FG $FG_DIM $ACCENT"')
cat >> "$P/chrome/userChrome.css" <<EOF
@media (prefers-color-scheme: light) {
  :root {
    --rr-bg: #$l_bg; --rr-surface: #$l_surface; --rr-hi: #$l_hi;
    --rr-sel: #$l_sel; --rr-fg: #$l_fg; --rr-dim: #$l_dim; --rr-accent: #$l_accent;
  }
}
EOF
info "$(L "Thunderbird like macOS Mail (profile $PROFILE)" "Thunderbird como Mail de macOS (perfil $PROFILE)")"
