#!/usr/bin/env bash
# Terminal: kitty (GPU-rendered, tabs and splits) in the RedRog style: the
# palette with the accent red as the ANSI red, the same translucent, blurred
# pane as Dolphin (KWin's own blur), macOS-style tabs with close buttons, a
# right-click menu (splits, panes, agent CLIs...), a red beam cursor with a
# short trail, and macOS-like shortcuts.
# It becomes the desktop's terminal (Dolphin, the menus, Ctrl+Alt+T).
# describe: kitty terminal: theme, tabs and shortcuts | terminal kitty: tema, pestañas y atajos

KC="$CONFIG_HOME/kitty"
MENU_DIR="$REAL_HOME/.local/lib/redrog/kitty"
run mkdir -p "$KC" "$MENU_DIR"

if [ "${DRY_RUN:-0}" = 1 ]; then
  info "write $KC/redrog-theme.conf, redrog-keys.conf, kitty.conf"
else
# Both variants (redrog-theme-dark.conf, redrog-theme-light.conf), the active
# one copied to redrog-theme.conf; the light/dark switch copies the other one
# and kitty reloads. (The body is not indented: it holds a heredoc.)
build_kitty() {
# ANSI colors: Arc's, with the theme's reds; on the light variant deeper ones
# that read on a light background, and black and white swapped
if [ "$THEME_VARIANT" = light ]; then
  c0=$FG c8=$FG_DIM c2=2e8540 c10=4f9e46 c3=a86d00 c11=c98a12 c4=2f6db5 c12=4877b1
  c5=8e4bb0 c13=a660c3 c6=1d7aa6 c14=2f95c2 c7=6e6a64 c15=8a857e
else
  c0=4b5164 c8=616981 c2=5ca75b c10=add488 c3=f6ab32 c11=fdc35f c4=4877b1 c12=8ca9bf
  c5=a660c3 c13=e2afec c6=5294e2 c14=73c5e2 c7=a9a9aa c15=fcfcfc
fi
# Colors and look, regenerated on every install from the palette
cat > "$KC/redrog-theme-$THEME_VARIANT.conf" <<EOF
# RedRog theme for kitty. Generated by modules/terminal: don't edit, it is
# overwritten on every install (put your own settings in kitty.conf).

# ── Palette ──
foreground              #$FG
background              #$DEEP
selection_foreground    #ffffff
selection_background    #$ACCENT
url_color               #$ACCENT_ALT
cursor                  #$ACCENT
cursor_text_color       #ffffff
# ANSI colors (see above)
color0  #$c0
color8  #$c8
color1  #$ACCENT
color9  #$ACCENT_ALT
color2  #$c2
color10 #$c10
color3  #$c3
color11 #$c11
color4  #$c4
color12 #$c12
color5  #$c5
color13 #$c13
color6  #$c6
color14 #$c14
color7  #$c7
color15 #$c15
mark1_background #$ACCENT

# ── Glass pane: the title bar's opacity (modules/window-decoration), so the
#    title bar and the terminal are one surface; KWin's blur behind ──
background_opacity      0.77
background_blur         1
dynamic_background_opacity yes

# ── Font ──
font_family             $FONT_MONO
font_size               $((FONT_SIZE + 1)).0
disable_ligatures       cursor
modify_font             cell_height 112%

# ── Cursor: red beam with a short trail ──
cursor_shape            beam
cursor_beam_thickness   1.6
cursor_blink_interval   0.6 ease-in-out
cursor_stop_blinking_after 12
cursor_trail            3
cursor_trail_decay      0.08 0.3

# ── Window ──
window_padding_width    6 12
placement_strategy      top-left
remember_window_size    yes
initial_window_width    110c
initial_window_height   30c
hide_window_decorations no
confirm_os_window_close -1

# ── Splits ──
enabled_layouts         splits,stack,tall
window_border_width     1pt
draw_minimal_borders    yes
active_border_color     #$ACCENT
inactive_border_color   #$SURFACE_HI
inactive_text_alpha     0.8
bell_border_color       #$ACCENT_ALT

# ── Tabs: rounded pills at the top, the active one in the accent ──
tab_bar_edge            top
# drawn by tab_bar.py: macOS-style tabs
tab_bar_style           custom
tab_bar_align           left
# like macOS: the tab bar appears with the second tab
tab_bar_min_tabs        2
tab_bar_margin_width    8
tab_bar_margin_height   6 2
tab_title_max_length    28
tab_title_template      "{title}"
tab_bar_background      none
# macOS-like: a lighter neutral pill for the active tab on a dark track
active_tab_foreground   #$FG
active_tab_background   #3b3b3a
active_tab_font_style   bold
inactive_tab_foreground #$FG_DIM
inactive_tab_background #$SURFACE
inactive_tab_font_style normal
tab_activity_symbol     "● "
bell_on_tab             "🔔 "

# ── Scrollback and scrollbar ──
scrollback_lines        20000
scrollbar               scrolled
scrollbar_handle_color  #$FG_DIM
scrollbar_track_color   #$SURFACE
scrollbar_radius        2
scrollbar_width         0.6
scrollbar_hover_width   1

# ── Bell and notifications ──
enable_audio_bell       no
visual_bell_duration    0.12 ease-out
visual_bell_color       #$ACCENT
window_alert_on_bell    yes
# desktop notification when a long command ends in an unfocused window
notify_on_cmd_finish    unfocused 15

# ── Misc ──
# the login shell (the session's $SHELL may point elsewhere)
shell                   $(getent passwd "$REAL_USER" | cut -d: -f7)
shell_integration       enabled
allow_hyperlinks        yes
copy_on_select          no
strip_trailing_spaces   smart
update_check_interval   0
EOF
}
for_each_variant build_kitty
cp "$KC/redrog-theme-$THEME_VARIANT.conf" "$KC/redrog-theme.conf"

# kitty.conf: created once, then it is the user's; it includes the theme
# and the RedRog shortcuts (both regenerated)
cat > "$KC/redrog-keys.conf" <<'EOF'
# RedRog shortcuts for kitty (on top of kitty's defaults, which use
# Ctrl+Shift). Generated by modules/terminal: don't edit.

# Tabs
map ctrl+shift+t   new_tab_with_cwd
map ctrl+shift+w   close_tab
map ctrl+tab       next_tab
map ctrl+shift+tab previous_tab
map ctrl+shift+r   set_tab_title
map alt+1 goto_tab 1
map alt+2 goto_tab 2
map alt+3 goto_tab 3
map alt+4 goto_tab 4
map alt+5 goto_tab 5
map alt+6 goto_tab 6
map alt+7 goto_tab 7
map alt+8 goto_tab 8
map alt+9 goto_tab -1

# Splits: D side by side, E one above the other, Q close, Z zoom
map ctrl+shift+d   launch --location=vsplit --cwd=current
map ctrl+shift+e   launch --location=hsplit --cwd=current
map ctrl+shift+q   close_window
map ctrl+shift+z   toggle_layout stack
map ctrl+alt+left  neighboring_window left
map ctrl+alt+right neighboring_window right
map ctrl+alt+up    neighboring_window up
map ctrl+alt+down  neighboring_window down
map ctrl+shift+alt+left  resize_window narrower
map ctrl+shift+alt+right resize_window wider
map ctrl+shift+alt+up    resize_window taller
map ctrl+shift+alt+down  resize_window shorter

# Search the scrollback, open a URL with the keyboard, clear
map ctrl+shift+f   launch --type=overlay --stdin-source=@screen_scrollback /usr/bin/less +G -R
map ctrl+shift+u   open_url_with_hints
map ctrl+shift+k   clear_terminal to_cursor active

# Transparency on the fly (Ctrl+Shift+A, then M more, L less, 1 opaque, D default)
map ctrl+shift+a>m set_background_opacity +0.05
map ctrl+shift+a>l set_background_opacity -0.05
map ctrl+shift+a>1 set_background_opacity 1
map ctrl+shift+a>d set_background_opacity default

# Reload this configuration
map ctrl+shift+f5  load_config_file
EOF
# Right click: RedRog's context menu (split, close, agents...). With Shift
# held, apps that use the mouse still get the menu.
echo "mouse_map right press ungrabbed launch --type=background --allow-remote-control --cwd=current $MENU_DIR/redrog-kitty-menu @active-kitty-window-id" >> "$KC/redrog-keys.conf"

if [ ! -f "$KC/kitty.conf" ] || ! grep -q 'redrog-theme.conf' "$KC/kitty.conf"; then
  [ -f "$KC/kitty.conf" ] && run cp "$KC/kitty.conf" "$KC/kitty.conf.bak"
  cat > "$KC/kitty.conf" <<'EOF'
# kitty configuration. RedRog's theme and shortcuts come from the two
# included files (regenerated by the installer); anything below them
# overrides them and is kept across reinstalls.
include redrog-theme.conf
include redrog-keys.conf

# Your settings:
EOF
fi
fi

# Tabs (tab_bar.py), the right-click menu (menu.qml run by
# redrog-kitty-menu), all in the palette's colors
if [ "$DRY_RUN" = 1 ]; then
  info "write $KC/tab_bar.py, $MENU_DIR/menu.qml, $MENU_DIR/redrog-kitty-menu"
else
  # in the active variant's colors (both kept for the light/dark switch)
  repaint_variants "$REDROG_ROOT/modules/terminal/tab_bar.py" "$KC/tab_bar.py"
  repaint_variants "$REDROG_ROOT/modules/terminal/menu.qml" "$MENU_DIR/menu.qml"
  install -m 755 "$REDROG_ROOT/modules/terminal/redrog-kitty-menu" "$MENU_DIR/redrog-kitty-menu"
fi

# KWin script that opens the menu with its corner at the pointer
KS="$DATA_HOME/kwin/scripts/redrog-menu-placement"
run rm -rf "$KS"
run mkdir -p "$(dirname "$KS")"
run cp -r "$REDROG_ROOT/modules/terminal/kwin-menu" "$KS"
kw --file kwinrc --group Plugins --key redrog-menu-placementEnabled true
run qdbus6 org.kde.KWin /KWin reconfigure >/dev/null 2>&1 || true
run qdbus6 org.kde.KWin /Scripting org.kde.kwin.Scripting.start >/dev/null 2>&1 || true   # load it now

# fish: no greeting instead of the full fastfetch summary,
# sourced right after the distribution's config (which sets that greeting)
FISH="$CONFIG_HOME/fish"
if [ -d "$FISH" ]; then
  run mkdir -p "$FISH/redrog"
  if [ "$DRY_RUN" = 1 ]; then
    info "write $FISH/redrog/greeting.fish"
  else
    sed -e "s/888680/$FG_DIM/; s/ef3340/$ACCENT/" "$REDROG_ROOT/modules/terminal/greeting.fish" > "$FISH/redrog/greeting.fish"
  fi
  line='source ~/.config/fish/redrog/greeting.fish  # RedRog'
  if ! grep -qF "$line" "$FISH/config.fish" 2>/dev/null; then
    if grep -q '^source .*cachyos-config.fish' "$FISH/config.fish" 2>/dev/null; then
      run sed -i "/^source .*cachyos-config.fish/a $line" "$FISH/config.fish"
    else
      [ "$DRY_RUN" = 1 ] || printf '\n%s\n' "$line" >> "$FISH/config.fish"
    fi
  fi
  # Homebrew only in interactive shells: the desktop session is started through
  # the login shell too, and Homebrew's python3 ahead of the system's (no dbus,
  # no Pillow) broke Panel Colorizer and other widgets' helper scripts
  # The Claude desktop app's terminal doesn't answer fish's terminal queries:
  # every new shell there waited 10 s and printed a warning. There fish
  # restarts itself once with the queries off (flags only apply at startup)
  if ! grep -q REDROG_FISH_NOQUERY "$FISH/config.fish" 2>/dev/null && [ "$DRY_RUN" != 1 ]; then
    { cat <<'FISHEOF'
# RedRog: the Claude desktop terminal doesn't answer fish's terminal queries;
# without this every new shell there waits 10 s and prints a warning
if test "$TERM_PROGRAM" = claude-desktop; and status is-interactive; and not set -q REDROG_FISH_NOQUERY
    set -gx REDROG_FISH_NOQUERY 1
    exec fish --features no-query-term
end
FISHEOF
      cat "$FISH/config.fish"; } > "$FISH/config.fish.new" && mv "$FISH/config.fish.new" "$FISH/config.fish"
  fi
  brew_line='eval "$(/home/linuxbrew/.linuxbrew/bin/brew shellenv fish)"'
  if grep -qxF "$brew_line" "$FISH/config.fish" 2>/dev/null; then
    run sed -i "s|^eval \"\$(/home/linuxbrew/.linuxbrew/bin/brew shellenv fish)\"\$|status is-interactive; and $brew_line  # RedRog: interactive only|" "$FISH/config.fish"
  fi
fi

# The desktop's terminal: Dolphin's "Open terminal", the menus, Ctrl+Alt+T
kw --file kdeglobals --group General --key TerminalApplication kitty
kw --file kdeglobals --group General --key TerminalService kitty.desktop
kw --file kglobalshortcutsrc --group services --group kitty.desktop --key _launch "Ctrl+Alt+T"
# Everything else that opens "a terminal" opens kitty too: $TERMINAL for
# scripts, xdg-terminal-exec (which GLib's "gio launch" asks first) and
# CachyOS's update notifier, launched with "gio launch" from a Terminal=true
# entry (GLib's own terminal list has no kitty): a user copy runs it in kitty.
# CachyOS Hello and the Kernel Manager pick kitty by themselves.
run mkdir -p "$CONFIG_HOME/environment.d"
[ "$DRY_RUN" = 1 ] || printf 'TERMINAL=kitty\n' > "$CONFIG_HOME/environment.d/50-redrog-terminal.conf"
[ "$DRY_RUN" = 1 ] || printf 'kitty.desktop\n' > "$CONFIG_HOME/xdg-terminals.list"
# The updater's own copy keeps the name and icon modules/apps gives it
# ("Actualizaciones", the RedRog icon): only its command changes, and its
# window is tied to it (StartupWMClass) so the dock shows that icon too
for entry in /usr/share/applications/arch-update.desktop; do
  [ -f "$entry" ] || continue
  dst="$DATA_HOME/applications/${entry##*/}"
  run mkdir -p "$DATA_HOME/applications"
  [ "$DRY_RUN" = 1 ] && continue
  [ -f "$dst" ] || cp "$entry" "$dst"
  sed -i -e 's/^Terminal=true/Terminal=false/' -e '/^StartupWMClass=/d' \
      -e '/^Exec=kitty /!s/^Exec=\(.*\)/Exec=kitty --class arch-update --title Actualizaciones \1/' \
      -e 's/--title Cachy-Update/--title Actualizaciones/' \
      -e '/^\[Desktop Entry\]/a StartupWMClass=arch-update' "$dst"
done
if has kitty; then
  run python3 -I "$REDROG_ROOT/lib/set-shortcut.py" kitty.desktop _launch Ctrl+Alt+T 2>/dev/null || true
  # running windows pick up the new theme
  run pkill -USR1 -x kitty 2>/dev/null || true
  info "$(L "kitty themed and set as the terminal" "kitty con el tema y como terminal predeterminada")"
else
  warn "$(L "kitty is not installed: sudo pacman -S kitty" "kitty no está instalado: sudo pacman -S kitty")"
fi

# fastfetch and hyfetch show the system as Arch Linux: the Arch logo and
# "Arch Linux" on the OS line (CachyOS is Arch underneath; /etc/os-release is
# untouched, so packages and tools still see CachyOS)
if has fastfetch && [ "$DRY_RUN" != 1 ]; then
  FF="$CONFIG_HOME/fastfetch/config.jsonc"
  if [ ! -f "$FF" ] || grep -q "RedRog" "$FF"; then
    mkdir -p "$(dirname "$FF")"
    cat > "$FF" <<'EOF'
// RedRog (modules/terminal): shown as Arch Linux (logo and OS line);
// everything else is fastfetch's default
{
  "$schema": "https://github.com/fastfetch-cli/fastfetch/raw/dev/doc/json_schema.json",
  "logo": { "source": "arch" },
  "modules": ["title", "separator", { "type": "os", "format": "Arch Linux {arch}" }, "host", "kernel", "uptime", "packages", "shell",
              "display", "de", "wm", "wmtheme", "theme", "icons", "font", "cursor", "terminal",
              "terminalfont", "cpu", "gpu", "memory", "swap", "disk", "localip", "battery",
              "poweradapter", "locale", "break", "colors"]
}
EOF
  fi
fi
# hyfetch detects the distribution itself and hands fastfetch its logo: Arch's
if has hyfetch && [ "$DRY_RUN" != 1 ]; then
  HF="$CONFIG_HOME/hyfetch.json"
  if [ -f "$HF" ]; then
    python3 -I - "$HF" <<'PY'
import json, sys
p = sys.argv[1]
d = json.load(open(p))
d["distro"] = "arch"
d["backend"] = "fastfetch"
json.dump(d, open(p, "w"), indent=4)
PY
  fi
fi
