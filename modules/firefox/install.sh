#!/usr/bin/env bash
# Firefox in RedRog colors: the UI (userChrome.css) and internal pages such as
# the new tab page or settings (userContent.css), which otherwise use Firefox's
# own violet gray (#2b2a33). Applied to the default profile; restart Firefox to see it.
# describe: RedRog colors in Firefox (UI and internal pages) | colores de RedRog en Firefox (interfaz y páginas internas)

FF=""
for d in "$CONFIG_HOME/mozilla/firefox" "$REAL_HOME/.mozilla/firefox"; do
  [ -f "$d/profiles.ini" ] && { FF="$d"; break; }
done
[ -n "$FF" ] || { info "$(L "Firefox has no profile yet: skipped" "Firefox no tiene perfil todavía: se omite")"; exit 0; }
PROFILE=$(awk -F= '/^\[Install/{f=1} f&&/^Default=/{print $2; exit}' "$FF/profiles.ini")
P="$FF/$PROFILE"            # with profile-sync-daemon this is a link to /run/user/…
[ -d "$P" ] || { warn "$(L "Firefox profile not found:" "no encuentro el perfil de Firefox") $PROFILE"; exit 0; }
if [ "$DRY_RUN" = 1 ]; then info "[dry-run] user.js, chrome/userChrome.css, chrome/userContent.css → $P"; exit 0; fi
mkdir -p "$P/chrome"

# Back up any user.js or stylesheet that RedRog did not generate
for f in user.js chrome/userChrome.css chrome/userContent.css; do
  if [ -f "$P/$f" ] && ! grep -q 'RedRog' "$P/$f"; then cp "$P/$f" "$P/$f.before-redrog"; fi
done

# Enable profile stylesheets and the dark "system" theme
cat > "$P/user.js" <<EOF
// Generated by RedRog (modules/firefox) — overwritten on reinstall
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
user_pref("extensions.activeThemeID", "default-theme@mozilla.org");
user_pref("browser.theme.toolbar-theme", 0);
user_pref("browser.theme.content-theme", 0);
user_pref("layout.css.prefers-color-scheme.content-override", 0);
EOF

# The stylesheets follow the system's light/dark mode (which the RedRog
# light/dark switch sets): the dark palette, then the light one inside
# @media (prefers-color-scheme: light)
ff_chrome() {
cat <<EOF
/* Generated by RedRog (modules/firefox) */
:root {
  --toolbar-bgcolor: #$BG !important;
  --toolbar-color: #$FG !important;
  --toolbar-field-background-color: #$SURFACE !important;
  --toolbar-field-focus-background-color: #$SURFACE !important;
  --toolbar-field-color: #$FG !important;
  --toolbar-field-focus-color: #$FG !important;
  --toolbar-field-border-color: #$SURFACE_HI !important;
  --toolbar-field-focus-border-color: #$ACCENT !important;
  --tab-selected-bgcolor: #$SURFACE !important;
  --tab-selected-textcolor: #$FG !important;
  --tab-hover-background-color: #$SURFACE_HI !important;
  --tabs-border-color: #$SURFACE_HI !important;
  --lwt-accent-color: #$BG !important;
  --lwt-text-color: #$FG !important;
  --arrowpanel-background: #$BG !important;
  --arrowpanel-color: #$FG !important;
  --arrowpanel-border-color: #$SURFACE_HI !important;
  --panel-separator-color: #$SURFACE_HI !important;
  --sidebar-background-color: #$BG !important;
  --sidebar-text-color: #$FG !important;
  --chrome-content-separator-color: #$SURFACE_HI !important;
  --urlbarView-highlight-background: #$SELECTION !important;
  --focus-outline-color: #$ACCENT !important;
}
#navigator-toolbox, #TabsToolbar, #nav-bar, #PersonalToolbar,
#titlebar, #sidebar-box, #sidebar-main, .sidebar-browser-stack {
  background-color: #$BG !important;
  color: #$FG !important;
}
/* Rounded active tab without the accent line */
.tab-background { border-radius: 8px !important; }
.tab-background[selected] { background: #$SURFACE !important; outline: 1px solid #$SURFACE_HI !important; }

/* Address bar: pill-shaped field and card-like dropdown */
#urlbar-background, #searchbar { border-radius: 14px !important; }
#urlbar[open] > #urlbar-background {
  background-color: #$BG !important;
  border: 1px solid #$SURFACE_HI !important;
  box-shadow: 0 12px 32px rgba(0, 0, 0, 0.5) !important;
}
.urlbarView { color: #$FG !important; }
.urlbarView-row { border-radius: 10px !important; }
.urlbarView-row[selected],
.urlbarView-row[selected] > .urlbarView-row-inner,
.urlbarView-row:hover > .urlbarView-row-inner {
  background-color: #$SELECTION !important;
  color: #$FG !important;
}
.urlbarView-row[selected] .urlbarView-action,
.urlbarView-row[selected] .urlbarView-url { color: #$FG_DIM !important; }
.urlbarView-url { color: #$FG_DIM !important; }
.search-one-offs, .urlbarView-body-inner { border-color: #$SURFACE_HI !important; }
EOF
}

ff_content() {
cat <<EOF
/* Generated by RedRog (modules/firefox) — internal pages */
@-moz-document url-prefix("about:") {
  :root {
    --in-content-page-background: #$BG !important;
    --in-content-page-color: #$FG !important;
    --in-content-box-background: #$SURFACE !important;
    --in-content-box-border-color: #$SURFACE_HI !important;
    --in-content-border-color: #$SURFACE_HI !important;
    --in-content-button-background: #$SURFACE_HI !important;
    --in-content-item-selected: #$SELECTION !important;
    --in-content-primary-button-background: #$ACCENT !important;
    --in-content-accent-color: #$ACCENT !important;
    --newtab-background-color: #$BG !important;
    --newtab-background-color-secondary: #$SURFACE !important;
    --newtab-text-primary-color: #$FG !important;
    --newtab-text-secondary-color: #$FG_DIM !important;
    --newtab-element-hover-color: #$SURFACE_HI !important;
    --background-color-canvas: #$BG !important;
    --background-color-box: #$SURFACE !important;
    --text-color: #$FG !important;
    --color-accent-primary: #$ACCENT !important;
  }
  body { background-color: #$BG !important; }
}
EOF
}
in_palette() {   # variant command...: the command with that variant's palette
  ( export REDROG_VARIANT=$1; HOME="$REAL_HOME" source "$REDROG_ROOT/lib/palette.sh"; "${@:2}" )
}
{
  in_palette dark ff_chrome
  echo '@media (prefers-color-scheme: light) {'
  in_palette light ff_chrome
  echo '}'
} > "$P/chrome/userChrome.css"
{
  in_palette dark ff_content
  # inside the page rule: the media query goes in it
  in_palette light ff_content | sed '0,/^@-moz-document .*{$/s//&\n@media (prefers-color-scheme: light) {/; $a }'
} > "$P/chrome/userContent.css"
info "$(L "Firefox profile $PROFILE (restart Firefox to see the changes)" "perfil de Firefox $PROFILE (reinícialo para ver los cambios)")"
