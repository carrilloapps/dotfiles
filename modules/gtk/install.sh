#!/usr/bin/env bash
# "RedRog" and "RedRog-Light" GTK themes: recolored copies of Arc-Dark and
# Arc-Lighter (arc-gtk-theme package).
# Arc ships its CSS compiled into gtk.gresource; lib/gtk-unpack.py extracts it so
# lib/recolor.py can change the CSS and images, and gtk.css imports the local files.
# describe: RedRog GTK theme (GTK apps and Firefox menus) | tema GTK RedRog (apps GTK y menús de Firefox)

# Both themes, "RedRog" (dark) and "RedRog-Light", for the light/dark switch
build_gtk() {
  local SRC=/usr/share/themes/$ARC_GTK GT="$DATA_HOME/themes/$REDROG_NAME" TMPG d
  if [ ! -d "$SRC" ]; then
    warn "$(L "arc-gtk-theme is not installed: GTK apps will use Breeze (./install.sh --packages)" \
              "arc-gtk-theme no está instalado: las apps GTK usarán Breeze (./install.sh --packages)")"
    return 0
  else
    run rm -rf "$GT"
    recolor "$SRC" "$GT"
    TMPG=$(mktemp -d)
    run python3 -I "$REDROG_ROOT/lib/gtk-unpack.py" "$SRC" "$TMPG" >/dev/null
    for d in "$TMPG"/gtk-*; do [ -d "$d" ] && recolor "$d" "$GT/$(basename "$d")"; done
    run rm -rf "$TMPG"
    run rm -f "$GT"/gtk-*/gtk.gresource
    run sed -i 's#resource:///org/gnome/arc-theme/##g' "$GT"/gtk-3.0/gtk.css "$GT"/gtk-3.0/gtk-dark.css \
                                                       "$GT"/gtk-4.0/gtk.css "$GT"/gtk-4.0/gtk-dark.css
    run sed -i "s/^Name=.*/Name=$REDROG_NAME/" "$GT/index.theme"
  fi
}
for_each_variant build_gtk
GTK_THEME=$THEME_ID
[ -d "$DATA_HOME/themes/$THEME_ID" ] || GTK_THEME=Breeze

for v in 3.0 4.0; do
  f="$CONFIG_HOME/gtk-$v/settings.ini"
  run mkdir -p "$(dirname "$f")"
  kw --file "$f" --group Settings --key gtk-theme-name "$GTK_THEME"
  kw --file "$f" --group Settings --key gtk-icon-theme-name "$ICON_THEME"
  kw --file "$f" --group Settings --key gtk-font-name "$FONT_UI $FONT_SIZE"
  kw --file "$f" --group Settings --key gtk-cursor-theme-name "$CURSOR_THEME"
  kw --file "$f" --group Settings --key gtk-application-prefer-dark-theme "$([ "$THEME_VARIANT" = dark ] && echo true || echo false)"
done
# GTK4/libadwaita and Electron read gsettings, not settings.ini
if has gsettings; then
  G=org.gnome.desktop.interface
  run gsettings set $G gtk-theme "$GTK_THEME"
  run gsettings set $G icon-theme "$ICON_THEME"
  run gsettings set $G color-scheme "$([ "$THEME_VARIANT" = dark ] && echo prefer-dark || echo prefer-light)"
  run gsettings set $G font-name "$FONT_UI $FONT_SIZE"
  run gsettings set $G document-font-name "$FONT_UI $FONT_SIZE"
  run gsettings set $G monospace-font-name "$FONT_MONO $FONT_SIZE"
  run gsettings set $G cursor-theme "$CURSOR_THEME"
fi
info "GTK: $GTK_THEME"

# GNOME (libadwaita) apps ignore GTK themes but read ~/.config/gtk-4.0/gtk.css:
# redrog.css gives them the RedRog palette and macOS traffic lights, like the
# KDE apps. KDE rewrites gtk.css when the colors change, so a small user
# service puts the import back whenever that happens.
G4="$CONFIG_HOME/gtk-4.0"
# Both variants are written (redrog-dark.css, redrog-light.css and their
# traffic lights) and the active one copied in place; the light/dark switch
# copies the other one. (The body is not indented: it holds heredocs.)
build_gnome_css() {
[ "$DRY_RUN" = 1 ] && return 0
mkdir -p "$G4"
cat > "$G4/redrog-$THEME_VARIANT.css" <<EOF
/* Generated by RedRog (modules/gtk): GNOME apps in RedRog colors */
@define-color accent_bg_color #$ACCENT;
@define-color accent_color #$ACCENT;
@define-color accent_fg_color #ffffff;
@define-color window_bg_color #$BG;
@define-color window_fg_color #$FG;
@define-color view_bg_color #$BG;
@define-color view_fg_color #$FG;
@define-color headerbar_bg_color #$BG;
@define-color headerbar_fg_color #$FG;
@define-color headerbar_backdrop_color #$BG;
@define-color headerbar_border_color #$SURFACE_HI;
@define-color sidebar_bg_color #$SIDEBAR;
@define-color sidebar_fg_color #$FG;
@define-color sidebar_backdrop_color #$SIDEBAR;
@define-color secondary_sidebar_bg_color #$BG;
@define-color card_bg_color #$SURFACE;
@define-color card_fg_color #$FG;
@define-color popover_bg_color #$SURFACE;
@define-color popover_fg_color #$FG;
@define-color dialog_bg_color #$SURFACE;
@define-color dialog_fg_color #$FG;
@define-color thumbnail_bg_color #$SURFACE;
@define-color borders #$SURFACE_HI;
:root {
  --accent-bg-color: #$ACCENT; --accent-color: #$ACCENT; --accent-fg-color: #ffffff;
  --window-bg-color: #$BG; --window-fg-color: #$FG;
  --view-bg-color: #$BG; --view-fg-color: #$FG;
  --headerbar-bg-color: #$BG; --headerbar-fg-color: #$FG; --headerbar-backdrop-color: #$BG;
  --headerbar-border-color: #$SURFACE_HI;
  --sidebar-bg-color: #$SIDEBAR; --sidebar-fg-color: #$FG; --sidebar-backdrop-color: #$SIDEBAR;
  --secondary-sidebar-bg-color: #$BG;
  --card-bg-color: #$SURFACE; --card-fg-color: #$FG;
  --popover-bg-color: #$SURFACE; --popover-fg-color: #$FG;
  --dialog-bg-color: #$SURFACE; --dialog-fg-color: #$FG;
  --thumbnail-bg-color: #$SURFACE;
  --border-color: #$SURFACE_HI;
}

/* macOS traffic lights, the same drawings as the KWin titlebar (redrog-lights/) */
windowcontrols { border-spacing: 0; }
windowcontrols > button.close, windowcontrols > button.minimize, windowcontrols > button.maximize,
windowcontrols > button.close.image-button, windowcontrols > button.minimize.image-button,
windowcontrols > button.maximize.image-button {
  min-width: 14px; min-height: 14px; padding: 0; margin: 0 3px;
  background: none; box-shadow: none; border: none; outline: none;
}
windowcontrols.start { margin-left: 6px; margin-right: 6px; }
windowcontrols > button > image {
  min-width: 14px; min-height: 14px; padding: 0; margin: 0;
  -gtk-icon-size: 0; color: transparent; background: none center / 14px 14px no-repeat;
}
windowcontrols > button.close > image { background-image: url("redrog-lights/close-active.svg"); }
windowcontrols > button.minimize > image { background-image: url("redrog-lights/minimize-active.svg"); }
windowcontrols > button.maximize > image { background-image: url("redrog-lights/maximize-active.svg"); }
windowcontrols:hover > button.close > image { background-image: url("redrog-lights/close-hover.svg"); }
windowcontrols:hover > button.minimize > image { background-image: url("redrog-lights/minimize-hover.svg"); }
windowcontrols:hover > button.maximize > image { background-image: url("redrog-lights/maximize-hover.svg"); }
windowcontrols > button.close:active > image { background-image: url("redrog-lights/close-pressed.svg"); }
windowcontrols > button.minimize:active > image { background-image: url("redrog-lights/minimize-pressed.svg"); }
windowcontrols > button.maximize:active > image { background-image: url("redrog-lights/maximize-pressed.svg"); }
windowcontrols:backdrop:not(:hover) > button > image { background-image: url("redrog-lights/close-inactive.svg"); }

/* Tighter, like macOS and the KDE apps: lower header bars and smaller buttons */
headerbar { min-height: 38px; padding: 0 4px; }
headerbar button, headerbar menubutton > button, headerbar splitbutton > button {
  min-height: 26px; min-width: 26px; padding: 2px 6px;
}
headerbar .title { font-weight: 600; }
.navigation-sidebar > row, .boxed-list > row { min-height: 34px; }
button.pill { padding: 8px 22px; }
EOF
  # one SVG per button and state, taken from the RedRog titlebar (Aurorae, made
  # by modules/window-decoration); Thunderbird and Notion use them too
  local AUR="$DATA_HOME/aurorae/themes/$REDROG_NAME"
  if [ -f "$AUR/close.svg" ]; then
    rm -rf "$G4/redrog-lights-$THEME_VARIANT"
    python3 -I - "$AUR" "$G4/redrog-lights-$THEME_VARIANT" <<'PY2'
import os, re, sys
src, dst = sys.argv[1:]
os.makedirs(dst, exist_ok=True)
for button in ("close", "minimize", "maximize"):
    svg = open(os.path.join(src, button + ".svg"), encoding="utf-8").read()
    head = re.match(r"<svg[^>]*>", svg).group(0)
    for state in ("active", "hover", "pressed", "inactive"):
        m = re.search(r'<g id="%s-center"[^>]*>.*?</g>' % state, svg, re.S)
        if m:
            open(os.path.join(dst, "%s-%s.svg" % (button, state)), "w", encoding="utf-8").write(
                head + m.group(0).replace('id="%s-center"' % state, "") + "</svg>")
PY2
  fi
}
for_each_variant build_gnome_css
if [ "$DRY_RUN" != 1 ]; then
  cp "$G4/redrog-$THEME_VARIANT.css" "$G4/redrog.css"
  rm -rf "$G4/redrog-lights"
  [ -d "$G4/redrog-lights-$THEME_VARIANT" ] && cp -r "$G4/redrog-lights-$THEME_VARIANT" "$G4/redrog-lights"
  mkdir -p "$REAL_HOME/.local/lib/redrog" "$CONFIG_HOME/systemd/user"
  cat > "$REAL_HOME/.local/lib/redrog/gtk4-import" <<'EOF'
#!/bin/bash
# RedRog: keeps "@import 'redrog.css';" in ~/.config/gtk-4.0/gtk.css (modules/gtk)
f="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0/gtk.css"
[ -f "${f%/*}/redrog.css" ] || exit 0
grep -q "redrog.css" "$f" 2>/dev/null || printf '\n@import "redrog.css";\n' >> "$f"
EOF
  chmod +x "$REAL_HOME/.local/lib/redrog/gtk4-import"
  cat > "$CONFIG_HOME/systemd/user/redrog-gtk4.path" <<EOF
[Unit]
Description=RedRog look for GNOME apps (watch gtk.css)

[Path]
PathChanged=$G4/gtk.css
PathExists=$G4

[Install]
WantedBy=default.target
EOF
  cat > "$CONFIG_HOME/systemd/user/redrog-gtk4.service" <<EOF
[Unit]
Description=RedRog look for GNOME apps

[Service]
Type=oneshot
ExecStart=$REAL_HOME/.local/lib/redrog/gtk4-import
EOF
  "$REAL_HOME/.local/lib/redrog/gtk4-import"
  systemctl --user daemon-reload
  systemctl --user enable --now redrog-gtk4.path >/dev/null 2>&1 || true
fi
info "$(L "GNOME apps with RedRog colors and traffic lights" "apps de GNOME con colores RedRog y semáforos")"
